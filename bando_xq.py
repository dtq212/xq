def timduongbando(idtu, idden, toado = None, is_chicongclienttudi = False):
    # Đường đi qua ít bản đồ nhất (cùng số bản đồ thì chọn đường đi bộ ngắn hơn), toado = (x, y) đang đứng ở idtu nếu biết.
    # Trả về [(id bản đồ, x cổng, y cổng, id bản đồ kế), ...] ([] nếu đã ở đích), None nếu không đi bộ tới được.
    # is_chicongclienttudi: chỉ đi qua cổng client tự tìm đường được (đặt TD_BANDO là client tự đi hết)
    if idtu == idden:
        return []
    if idtu not in BANDOCONG_MAP:
        return None
    hangdoi = [(0, 0., idtu, toado, ())]
    datham = set()
    while hangdoi:
        solan, quangduong, idbando, vitri, duongdi = heapq.heappop(hangdoi)
        if idbando == idden:
            return list(duongdi)
        if idbando in datham:
            continue
        datham.add(idbando)
        for idke, x, y, xden, yden in BANDOCONG_MAP.get(idbando, ((),))[1]:
            if idke in datham or (is_chicongclienttudi and (idbando, idke) in _CONGNGOAIMAPLINK):
                continue
            buoc = math.hypot(x - vitri[0], y - vitri[1]) if vitri else 0.
            heapq.heappush(hangdoi, (solan + 1, quangduong + buoc, idke, (xden, yden) if xden is not None else None, duongdi + ((idbando, x, y, idke),)))
    return None


def get_solanchuyenbando(idtu, idden, is_chicongclienttudi = False):
    # Số lần qua cổng ít nhất từ idtu tới idden (0 = cùng bản đồ), None nếu không đi bộ tới được
    duongdi = timduongbando(idtu, idden, is_chicongclienttudi = is_chicongclienttudi)
    return None if duongdi is None else len(duongdi)


def get_is_nendibotoibando(idtu, idden, sochuyentoida = SOLANCHUYENBANDOTOIDA, is_chicongclienttudi = False):
    # Có nên tự đi bộ từ idtu tới idden không: tới được và qua không quá sochuyentoida cổng
    solan = get_solanchuyenbando(idtu, idden, is_chicongclienttudi)
    return solan is not None and solan <= sochuyentoida
