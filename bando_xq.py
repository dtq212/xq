# Dấu thanh (huyền, sắc, hỏi, ngã, nặng) dạng tổ hợp: chuẩn hoá về cuối mỗi từ để "Nguỵ" (kiểu cũ) và "Ngụy" so khớp được với nhau
_DAUTHANHs = frozenset("̣̀́̉̃")


def _chuanhoaten(ten):
    tus = []
    for tu in unicodedata.normalize("NFD", ten).lower().split():
        tus.append("".join(c for c in tu if c not in _DAUTHANHs) + "".join(c for c in tu if c in _DAUTHANHs))
    return " ".join(tus)


_IDBANDOTHEOTEN_MAP = {}
for _idbando in sorted(BANDOCONG_MAP, reverse = True):
    if BANDOCONG_MAP[_idbando][0]:
        _ten = _chuanhoaten(BANDOCONG_MAP[_idbando][0])
        _IDBANDOTHEOTEN_MAP[_ten] = _idbando
        # "Tề Quốc" cũng tra được bằng "Tề" (mô tả Tàng Bảo Đồ ghi tên nước không có "Quốc")
        if _ten.endswith(" " + _chuanhoaten("Quốc")):
            _IDBANDOTHEOTEN_MAP[_ten.rsplit(" ", 1)[0]] = _idbando


